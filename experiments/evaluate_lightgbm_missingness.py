def _validate_feature_schema(
    example: BacktestExample,
    baseline: BaselineConfig,
    selected_feature_names: Sequence[str],
) -> np.ndarray:
    baseline_row = seasonal_forecast(example.window, baseline)[0]
    names, _ = build_feature_row(example.window, 0, baseline_row, {}, {})
    if len(names) != 88:
        raise ValueError(f"Original WLCR full feature schema changed: {len(names)}")
    columns = np.asarray(ORIGINAL_WLCR_SELECTED_COLUMNS, dtype=np.int64)
    if columns.tolist() != [0, *range(16, 88)]:
        raise RuntimeError("Original WLCR traffic-only 73D column map changed")
    if [names[int(index)] for index in columns] != list(selected_feature_names):
        raise ValueError(
            "replayed traffic-only feature names do not match the frozen booster manifest"
        )
    return columns


def replay_original_wlcr(
    examples: Sequence[BacktestExample],
    baseline: BaselineConfig,
    columns: np.ndarray,
    boosters: Sequence[Any],
    *,
    num_threads: int,
) -> tuple[np.ndarray, dict[str, float]]:
    """Rebuild all request-local 73D matrices then call the frozen CPU trees."""
    if len(examples) != 5_110:
        raise ValueError(f"expected 5,110 held-out examples, found {len(examples)}")
    started = time.perf_counter()
    # Empty maps are intentional: every selected feature is horizon or one of
    # the four traffic blocks.  This call does not open parameter/weather CSVs.
    full_features, _ = build_test_matrix(
        tuple(example.window for example in examples), baseline, {}, {}
    )
    feature_seconds = time.perf_counter() - started
    selected = np.ascontiguousarray(
        np.asarray(full_features, dtype=np.float32)[:, columns], dtype=np.float32
    )
    expected_shape = (len(examples) * FORECAST_HOURS, len(ORIGINAL_WLCR_SELECTED_COLUMNS))
    if selected.shape != expected_shape:
        raise ValueError(f"Original WLCR replay matrix shape changed: {selected.shape}")

    inference_started = time.perf_counter()
    values = np.empty((len(selected), TARGET_COUNT), dtype=np.float64)
    for metric, booster in enumerate(boosters):
        output = np.asarray(booster.predict(selected, num_threads=num_threads))
        if output.shape != (len(selected),):
            raise ValueError(
                f"Original WLCR booster {metric} returned wrong shape: {output.shape}"
            )
        values[:, metric] = np.maximum(np.expm1(output), OUTPUT_FLOOR)
    inference_seconds = time.perf_counter() - inference_started
    prediction = np.ascontiguousarray(
        values.reshape(len(examples), FORECAST_HOURS, TARGET_COUNT), dtype=np.float32
    )
    if not np.all(np.isfinite(prediction)) or np.any(prediction <= 0.0):
        raise FloatingPointError("Original WLCR replay produced invalid predictions")
    return prediction, {
        "feature_construction_seconds": float(feature_seconds),
        "booster_prediction_seconds": float(inference_seconds),
        "total_replay_seconds": float(feature_seconds + inference_seconds),
    }


def threshold_hit_score(
    actual: np.ndarray, prediction: np.ndarray, frozen_thresholds: np.ndarray
) -> dict[str, object]:
    y = np.asarray(actual, dtype=np.float64).reshape(-1, TARGET_COUNT)
    p = np.asarray(prediction, dtype=np.float64).reshape(-1, TARGET_COUNT)
    thresholds = np.asarray(frozen_thresholds, dtype=np.float64)
    complete = np.all(np.isfinite(y), axis=1) & np.all(np.isfinite(p), axis=1)
    selected = complete & np.all(y >= thresholds[None, :], axis=1)
    if not np.any(selected) or np.any(y[selected] <= 0.0):
        raise ValueError("frozen threshold filter retained no strictly-positive hours")
    error = np.mean(np.abs(y[selected] - p[selected]) / y[selected], axis=1)
    limits = np.asarray((0.2, 0.3, 0.4, 0.5), dtype=np.float64)
    rates = [float(np.mean(error < threshold)) for threshold in limits]
    return {
        "n_hours": int(np.sum(selected)),
        "frozen_training_thresholds": thresholds.tolist(),
        "mean_mape": float(np.mean(error)),
        "rates": rates,
        "score": float(np.mean(rates)),
    }


def forecast_metrics(
    actual: np.ndarray,
    prediction: np.ndarray,
    mase_scales: np.ndarray,
    cells: np.ndarray,
) -> dict[str, object]:
    """The scalar metric definitions used by Revision-8 comparative analysis."""
    y = np.asarray(actual, dtype=np.float64)
    p = np.asarray(prediction, dtype=np.float64)
    scales = np.asarray(mase_scales, dtype=np.float64)
    cell_values = np.asarray(cells).astype(str)
    if y.shape != p.shape or y.shape[1:] != (FORECAST_HOURS, TARGET_COUNT):
        raise ValueError("forecast metric arrays are misaligned")
    indicator_rows: list[dict[str, float | int | str]] = []
    for metric in range(TARGET_COUNT):
        valid = np.isfinite(y[..., metric]) & np.isfinite(p[..., metric])
        yy = y[..., metric][valid]
        pp = p[..., metric][valid]
        if not len(yy):
            raise ValueError(f"indicator {metric} has no valid prediction/target pairs")
        absolute = np.abs(yy - pp)
        scale_grid = np.broadcast_to(scales[:, None, metric], y[..., metric].shape)
        scale_valid = valid & np.isfinite(scale_grid) & (scale_grid > 1e-12)
        if not np.any(scale_valid):
            raise ValueError(f"indicator {metric} has no valid MASE scales")
        mase = np.mean(
            np.abs(y[..., metric][scale_valid] - p[..., metric][scale_valid])
            / scale_grid[scale_valid]
        )
        indicator_rows.append(
            {
                "indicator": METRIC_NAMES[metric],
                "n": int(np.sum(valid)),
                "mae": float(np.mean(absolute)),
                "rmse": float(np.sqrt(np.mean((yy - pp) ** 2))),
                "wape": float(np.sum(absolute) / max(np.sum(np.abs(yy)), 1e-12)),
                "smape": float(
                    np.mean(
                        2.0
                        * absolute
                        / np.maximum(np.abs(yy) + np.abs(pp), 1e-12)
                    )
                ),
                "mase": float(mase),
            }
        )
    valid_all = np.isfinite(y) & np.isfinite(p)
    pooled_abs = np.abs(y[valid_all] - p[valid_all])
    pooled_wape = float(
        np.sum(pooled_abs) / max(np.sum(np.abs(y[valid_all])), 1e-12)
    )
    cell_wapes: list[float] = []
    for cell in sorted(set(cell_values.tolist())):
        selected = cell_values == cell
        valid = np.isfinite(y[selected]) & np.isfinite(p[selected])
        numerator = np.sum(np.abs(y[selected][valid] - p[selected][valid]))
        denominator = np.sum(np.abs(y[selected][valid]))
        if denominator > 0.0:
            cell_wapes.append(float(numerator / denominator))
    if not cell_wapes:
        raise ValueError("no cells with valid WAPE denominator")
    horizon_wape: list[float] = []
    for horizon in range(FORECAST_HOURS):
        valid = np.isfinite(y[:, horizon, :]) & np.isfinite(p[:, horizon, :])
        numerator = np.sum(
            np.abs(y[:, horizon, :][valid] - p[:, horizon, :][valid])
        )
        denominator = np.sum(np.abs(y[:, horizon, :][valid]))
        horizon_wape.append(float(numerator / max(denominator, 1e-12)))
    return {
        "per_indicator": indicator_rows,
        "macro_indicator": {
            key: float(np.mean([float(row[key]) for row in indicator_rows]))
            for key in ("mae", "rmse", "wape", "smape", "mase")
        },
        "pooled_wape": pooled_wape,
        "macro_cell_wape": float(np.mean(cell_wapes)),
        "median_cell_wape": float(np.median(cell_wapes)),
        "cell_count": int(len(cell_wapes)),
        "per_horizon_wape": horizon_wape,
    }


def metric_payload(
    prediction: np.ndarray, bundle: HoldoutBundle
) -> tuple[dict[str, object], dict[str, object], dict[str, object]]:
    metrics = forecast_metrics(
        bundle.actual, prediction, bundle.mase_scales, bundle.cells
    )
    hits = threshold_hit_score(bundle.actual, prediction, bundle.frozen_thresholds)
    values = {
        "macro_wape": float(metrics["macro_indicator"]["wape"]),
        "pooled_wape": float(metrics["pooled_wape"]),
        "macro_cell_wape": float(metrics["macro_cell_wape"]),
        "median_cell_wape": float(metrics["median_cell_wape"]),
        "mase": float(metrics["macro_indicator"]["mase"]),
        "smape": float(metrics["macro_indicator"]["smape"]),
        "mae": float(metrics["macro_indicator"]["mae"]),
        "rmse": float(metrics["macro_indicator"]["rmse"]),
        "threshold_hit_score": float(hits["score"]),
        "threshold_hit_n_hours": int(hits["n_hours"]),
        "threshold_hit_mean_mape": float(hits["mean_mape"]),
    }
    return values, metrics, hits


def t_interval(values: Sequence[float]) -> tuple[float, float, float, float]:
    mean = float(np.mean(np.asarray(values, dtype=np.float64)))
    if len(values) == 1:
        return mean, 0.0, mean, mean
    sd = float(np.std(np.asarray(values, dtype=np.float64), ddof=1))
    half = T95_DF4 * sd / math.sqrt(len(values))
    return mean, sd, mean - half, mean + half


def aggregate_seed_rows(rows: Sequence[Mapping[str, object]]) -> list[dict[str, object]]:
    groups: dict[tuple[object, ...], list[Mapping[str, object]]] = {}
    group_fields = (
        "method",
        "label",
        "training_view",
        "model_state",
        "mechanism",
        "mechanism_display",
        "requested_rate",
        "scenario",
    )
    numeric_fields = (
        "macro_wape",
        "pooled_wape",
        "macro_cell_wape",
        "median_cell_wape",
        "mase",
        "smape",
        "mae",
        "rmse",
        "threshold_hit_score",
        "threshold_hit_mean_mape",
        "unique_original_missing_rate",
        "unique_selected_for_corruption_rate",
        "unique_newly_removed_rate",
        "unique_newly_removed_fraction_of_observed",
        "unique_final_total_missing_rate",
        "exposure_original_missing_rate",
        "exposure_selected_for_corruption_rate",
        "exposure_newly_removed_rate",
        "exposure_newly_removed_fraction_of_observed",
        "exposure_final_total_missing_rate",
    )
    for row in rows:
        key = tuple(row[field] for field in group_fields)
        groups.setdefault(key, []).append(row)
    output: list[dict[str, object]] = []
    for key in sorted(groups, key=lambda item: tuple(str(value) for value in item)):
        selected = groups[key]
        item = {field: value for field, value in zip(group_fields, key)}
        item["corruption_seed_count"] = int(len(selected))
        item["corruption_seeds"] = ",".join(
            str(int(row["corruption_seed"])) for row in selected
        )
        item["threshold_hit_n_hours"] = int(selected[0]["threshold_hit_n_hours"])
        for field in numeric_fields:
            mean, sd, low, high = t_interval(
                [float(row[field]) for row in selected]
            )
            item[field] = mean
            item[f"{field}_sd"] = sd
            item[f"{field}_ci_low"] = low
            item[f"{field}_ci_high"] = high
        output.append(item)
    return output


def _output_manifest(output: Path) -> list[dict[str, object]]:
    records: list[dict[str, object]] = []
    for path in sorted(output.rglob("*")):
        if not path.is_file() or path.name == "manifest.json":
            continue
        records.append(
            {
                "path": str(path.relative_to(output)),
                "size_bytes": int(path.stat().st_size),
                "sha256": sha256_file(path),
            }
        )
    return records


def _preflight_output(output: Path) -> None:
    if output.exists() and any(output.iterdir()):
        raise FileExistsError(
            f"refusing to mix a new stress run with existing output: {output}; "
            "choose a fresh Revision-9 output directory"
        )
    output.mkdir(parents=True, exist_ok=True)


def _reference_prediction(root: Path, requested: str | Path) -> tuple[Path, np.ndarray]:
    source = resolve_inside(root, requested, strict=True)
    values = np.load(source, allow_pickle=False)
    if values.shape != (5_110, FORECAST_HOURS, TARGET_COUNT):
        raise ValueError(f"aligned Original WLCR prediction shape changed: {values.shape}")
    if not np.all(np.isfinite(values)) or np.any(values <= 0.0):
        raise ValueError("aligned Original WLCR prediction contains invalid values")
    return source, np.ascontiguousarray(values, dtype=np.float32)


def align_reference_prediction(
    reference: np.ndarray,
    source: Path,
    bundle: HoldoutBundle,
) -> np.ndarray:
    """Align persisted tree predictions to the reconstructed request order."""
    # This helper is intentionally usable in an isolated test without
    # initializing the CPU worker's global dependency bindings.
    import numpy as np

    order_path = source / "holdout_order.csv"
    if not order_path.is_file():
        raise FileNotFoundError(f"missing persisted prediction order: {order_path}")
    with order_path.open("r", encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if len(rows) != len(reference) or len(rows) != len(bundle.identity_rows):
        raise ValueError("persisted prediction order does not match the holdout size")
    positions: dict[tuple[str, str], int] = {}
    for position, row in enumerate(rows):
        key = (str(row.get("cell", "")), str(row.get("target_start", "")))
        if not all(key) or key in positions:
            raise ValueError("persisted prediction order has an invalid or duplicate request key")
        positions[key] = position
    expected = [
        (str(row["cell"]), str(row["target_start"]))
        for row in bundle.identity_rows
    ]
    if set(positions) != set(expected):
        raise ValueError("persisted prediction order and reconstructed holdout keys differ")
    indices = np.asarray([positions[key] for key in expected], dtype=np.int64)
    return np.ascontiguousarray(reference[indices], dtype=np.float32)


def _check_clean_replay(
    *,
    prediction: np.ndarray,
    reference: np.ndarray,
    tolerance: float,
) -> tuple[float, bool]:
    if prediction.shape != reference.shape:
        raise ValueError("clean replay prediction/reference shape mismatch")
    maximum = float(
        np.max(
            np.abs(
                np.asarray(prediction, dtype=np.float64)
                - np.asarray(reference, dtype=np.float64)
            )
        )
    )
    return maximum, bool(maximum <= tolerance)


