def run_outer(args: argparse.Namespace) -> int:
    """Launch the model replay under the bundled CPU-only LightGBM runtime."""
    root = project_root()
    output = resolve_output(root, args.output)
    runtime = resolve_inside(root, args.runtime_deps, strict=True)
    if not runtime.is_dir():
        raise ValueError(f"runtime dependency directory is not a directory: {runtime}")
    command = [
        sys.executable,
        str(Path(__file__).resolve()),
        "--worker",
        "--output",
        str(output),
        "--original-wlcr-source",
        str(args.original_wlcr_source),
        "--clean-reference",
        str(args.clean_reference),
        "--clean-replay-atol",
        str(args.clean_replay_atol),
        "--num-threads",
        str(args.num_threads),
    ]
    if args.smoke:
        command.append("--smoke")
    worker_environment = os.environ.copy()
    worker_environment["PYTHONPATH"] = os.pathsep.join((str(runtime), str(root)))
    worker_environment["PYTHONDONTWRITEBYTECODE"] = "1"
    worker_environment["CUDA_VISIBLE_DEVICES"] = ""
    for key in (
        "OMP_NUM_THREADS",
        "MKL_NUM_THREADS",
        "OPENBLAS_NUM_THREADS",
        "NUMEXPR_NUM_THREADS",
    ):
        worker_environment[key] = str(args.num_threads)
    completed = subprocess.run(command, cwd=str(root), env=worker_environment, check=False)
    return int(completed.returncode)


def parser() -> argparse.ArgumentParser:
    value = argparse.ArgumentParser(description=__doc__)
    value.add_argument("--output", default=str(DEFAULT_OUTPUT))
    value.add_argument("--original-wlcr-source", default=str(ORIGINAL_WLCR_SOURCE))
    value.add_argument("--clean-reference", default=str(ORIGINAL_WLCR_ALIGNMENT))
    value.add_argument("--runtime-deps", default=str(RUNTIME_DEPS))
    value.add_argument("--clean-replay-atol", type=float, default=2e-4)
    value.add_argument("--num-threads", type=int, default=1)
    value.add_argument("--smoke", action="store_true")
    value.add_argument("--worker", action="store_true", help=argparse.SUPPRESS)
    return value


def main(argv: Sequence[str] | None = None) -> int:
    args = parser().parse_args(argv)
    if args.worker:
        return run_worker(args)
    return run_outer(args)


if __name__ == "__main__":
    raise SystemExit(main())
