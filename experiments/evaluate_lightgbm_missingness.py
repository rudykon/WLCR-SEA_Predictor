def project_root() -> Path:
    return Path(__file__).resolve().parents[1]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_array(values: object, *, dtype: object) -> str:
    """Hash contiguous C-order array content after an explicit dtype coercion."""
    array = np.ascontiguousarray(np.asarray(values, dtype=dtype))
    return hashlib.sha256(array.tobytes(order="C")).hexdigest()


def canonical_json_sha256(payload: object) -> str:
    data = json.dumps(
        payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    return hashlib.sha256(data).hexdigest()


def atomic_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with temporary.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, path)


def atomic_csv(path: Path, rows: Sequence[Mapping[str, object]]) -> None:
    if not rows:
        raise ValueError(f"refusing to write empty CSV: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with temporary.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, path)


def atomic_npy(path: Path, values: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with temporary.open("wb") as handle:
        np.save(handle, np.ascontiguousarray(np.asarray(values)), allow_pickle=False)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, path)


def resolve_inside(root: Path, value: str | Path, *, strict: bool) -> Path:
    requested = Path(value)
    if not requested.is_absolute():
        requested = root / requested
    resolved = requested.resolve(strict=strict)
    if not resolved.is_relative_to(root):
        raise ValueError(f"path escapes the project root: {value}")
    return resolved


def resolve_output(root: Path, value: str | Path) -> Path:
    output = resolve_inside(root, value, strict=False)
    allowed = (root / OUTPUT_ROOT).resolve(strict=False)
    if output == allowed or not output.is_relative_to(allowed):
        raise ValueError(f"outputs must be in a child directory of {OUTPUT_ROOT}")
    return output


def file_provenance(root: Path, path: Path) -> dict[str, object]:
    resolved = path.resolve(strict=True)
    if (
        not resolved.is_relative_to(root)
        or not resolved.is_file()
        or path.is_symlink()
    ):
        raise ValueError(f"invalid local evidence asset: {path}")
    return {
        "path": str(resolved.relative_to(root)),
        "size_bytes": int(resolved.stat().st_size),
        "sha256": sha256_file(resolved),
    }


def _timestamp_hour(value: datetime) -> int:
    epoch = datetime(1970, 1, 1)
    return int((value - epoch).total_seconds() // 3600)


def _rows_to_array(rows: Sequence[TrafficRow]) -> np.ndarray:
    values = np.full((len(rows), TARGET_COUNT), np.nan, dtype=np.float64)
    for row_index, row in enumerate(rows):
        for metric, value in enumerate(row.metrics):
            if value is not None:
                values[row_index, metric] = float(value)
    return values


def history_mase_scale(history: np.ndarray) -> np.ndarray:
    """Byte-for-byte semantic counterpart of neural.history_mase_scale."""
    if history.shape != (INPUT_HOURS, TARGET_COUNT):
        raise ValueError(f"unexpected history shape: {history.shape}")
    differences = np.abs(history[168:] - history[:-168])
    scales = np.full(TARGET_COUNT, np.nan, dtype=np.float32)
    for metric in range(TARGET_COUNT):
        finite = np.isfinite(differences[:, metric])
        if np.any(finite):
            value = float(np.mean(differences[finite, metric]))
            if value > 1e-12:
                scales[metric] = value
    return scales


def _identity_digest(rows: Sequence[Mapping[str, object]]) -> str:
    fields = (
        "holdout_position",
        "dataset_index",
        "cell",
        "target_start",
        "history_end",
        "target_start_hour",
        "history_end_hour",
    )
    text = "".join(
        "|".join(str(row[field]) for field in fields) + "\n" for row in rows
    )
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _build_holdout_bundle(train_path: Path) -> HoldoutBundle:
    """Reconstruct neural's insertion-order 336-to-24 continuous requests.

    ``train_neural_baselines.build_window_arrays`` uses the first-occurrence cell
    order of the CSV and appends only continuous candidates.  Reimplementing
    that small, data-only part here avoids importing PyTorch into the isolated
    LightGBM runtime while preserving its dataset-index and holdout ordering.
    """
    rows = read_traffic(train_path)
    grouped: dict[str, list[TrafficRow]] = {}
    for row in rows:
        grouped.setdefault(row.cell, []).append(row)

    all_dataset_count = 0
    candidate_count = 0
    discontinuities: list[dict[str, object]] = []
    date_counts: dict[str, int] = {}
    holdout_examples: list[BacktestExample] = []
    holdout_indices: list[int] = []
    holdout_masks: list[np.ndarray] = []
    holdout_actuals: list[np.ndarray] = []
    holdout_scales: list[np.ndarray] = []
    holdout_cells: list[str] = []
    holdout_target_hours: list[int] = []
    holdout_history_hours: list[int] = []
    final_train_targets: list[np.ndarray] = []

    for cell, cell_rows in grouped.items():
        if any(
            right.timestamp <= left.timestamp
            for left, right in zip(cell_rows[:-1], cell_rows[1:])
        ):
            raise ValueError(f"training timestamps are not strictly ordered for cell {cell}")
        for index in range(INPUT_HOURS, len(cell_rows) - FORECAST_HOURS + 1, 24):
            candidate_count += 1
            start = index - INPUT_HOURS
            stop = index + FORECAST_HOURS
            local = cell_rows[start:stop]
            gaps = [
                (offset, int((right.timestamp - left.timestamp).total_seconds() // 3600))
                for offset, (left, right) in enumerate(zip(local[:-1], local[1:]))
                if right.timestamp - left.timestamp != timedelta(hours=1)
            ]
            if gaps:
                discontinuities.append(
                    {
                        "cell": cell,
                        "target_start": cell_rows[index].timestamp.strftime(
                            "%Y-%m-%d %H:%M:%S"
                        ),
                        "gaps": [
                            {"after_offset": offset, "elapsed_hours": elapsed}
                            for offset, elapsed in gaps
                        ],
                    }
                )
                continue

            history = tuple(cell_rows[start:index])
            actual_rows = tuple(cell_rows[index:stop])
            target_start = actual_rows[0].timestamp
            history_end = history[-1].timestamp
            if history_end + timedelta(hours=1) != target_start:
                raise ValueError("history does not end one hour before its target")
            window = TestWindow(
                index=all_dataset_count,
                cell=cell,
                rows=history,
                gaps=(),
            )
            example = BacktestExample(window=window, actuals=actual_rows)
            history_array = _rows_to_array(history)
            actual_array = _rows_to_array(actual_rows).astype(np.float32)
            target_day = target_start.date()
            date_key = target_day.isoformat()
            date_counts[date_key] = date_counts.get(date_key, 0) + 1

            if target_day in FINAL_TRAIN_DATES:
                final_train_targets.append(actual_array)
            if target_day in HOLDOUT_DATES:
                holdout_examples.append(example)
                holdout_indices.append(all_dataset_count)
                holdout_masks.append(np.isfinite(history_array).astype(np.uint8))
                holdout_actuals.append(actual_array)
                holdout_scales.append(history_mase_scale(history_array))
                holdout_cells.append(cell)
                holdout_target_hours.append(_timestamp_hour(target_start))
                holdout_history_hours.append(_timestamp_hour(history_end))
            all_dataset_count += 1

    if candidate_count != 11_686 or all_dataset_count != 11_685:
        raise ValueError(
            "registered training window count changed: "
            f"candidates={candidate_count}, continuous={all_dataset_count}"
        )
    if len(holdout_examples) != 5_110:
        raise ValueError(f"expected 5,110 Revision-8 holdout requests, found {len(holdout_examples)}")
    if len(final_train_targets) != 6_575:
        raise ValueError(
            f"expected 6,575 pre-holdout requests, found {len(final_train_targets)}"
        )

    actual = np.stack(holdout_actuals, axis=0).astype(np.float32)
    original_masks = np.stack(holdout_masks, axis=0).astype(np.uint8)
    scales = np.stack(holdout_scales, axis=0).astype(np.float32)
    cells = np.asarray(holdout_cells, dtype="U64")
    target_hours = np.asarray(holdout_target_hours, dtype=np.int64)
    history_hours = np.asarray(holdout_history_hours, dtype=np.int64)
    dataset_indices = np.asarray(holdout_indices, dtype=np.int64)
    if original_masks.shape != (5_110, INPUT_HOURS, TARGET_COUNT):
        raise ValueError(f"unexpected holdout mask shape: {original_masks.shape}")
    if actual.shape != (5_110, FORECAST_HOURS, TARGET_COUNT):
        raise ValueError(f"unexpected holdout target shape: {actual.shape}")
    if not np.all(history_hours + 1 == target_hours):
        raise ValueError("history/target hour alignment changed")

    # Original field loss is synchronized across the four indicators.  This is
    # an observed-data assertion; asynchronous loss below is solely controlled
    # stress corruption.
    if any(
        not np.array_equal(original_masks[..., 0], original_masks[..., metric])
        for metric in range(1, TARGET_COUNT)
    ):
        raise ValueError("registered original indicator masks are no longer synchronous")

    identity_rows: list[dict[str, object]] = []
    for position, (example, dataset_index, target_hour, history_hour) in enumerate(
        zip(holdout_examples, dataset_indices, target_hours, history_hours)
    ):
        identity_rows.append(
            {
                "holdout_position": int(position),
                "dataset_index": int(dataset_index),
                "cell": str(example.window.cell),
                "target_start": example.window.target_start.strftime(
                    "%Y-%m-%d %H:%M:%S"
                ),
                "history_end": example.window.rows[-1].timestamp.strftime(
                    "%Y-%m-%d %H:%M:%S"
                ),
                "target_start_hour": int(target_hour),
                "history_end_hour": int(history_hour),
            }
        )
    identity_sha256 = _identity_digest(identity_rows)
    first = identity_rows[0]
    last = identity_rows[-1]
    # The historical Revision-3 CSV was emitted in its own sorted-example
    # order, while the Revision-8 neural dataset uses train-CSV first-cell
    # occurrence order.  Do not conflate those two orders here: the rate-zero
    # prediction-to-NPY replay below is the stronger exact ordering check.

    final_targets = np.stack(final_train_targets, axis=0).astype(np.float32)
    flat = final_targets.reshape(-1, TARGET_COUNT)
    complete = np.all(np.isfinite(flat), axis=1)
    if not np.any(complete):
        raise ValueError("pre-holdout layer has no complete targets for thresholds")
    frozen_thresholds = np.quantile(
        flat[complete], 0.05, axis=0, method="linear"
    ).astype(np.float64)
    if not np.all(np.isfinite(frozen_thresholds)) or np.any(frozen_thresholds <= 0.0):
        raise ValueError("frozen low-activity thresholds are invalid")

    report = {
        "training_rows": int(len(rows)),
        "unique_cells": int(len(grouped)),
        "candidate_windows": int(candidate_count),
        "continuous_windows": int(all_dataset_count),
        "holdout_windows": int(len(holdout_examples)),
        "final_train_windows": int(len(final_train_targets)),
        "date_counts": date_counts,
        "discontinuous_windows": discontinuities,
        "original_indicator_masks_synchronous": True,
        "first_holdout_identity": first,
        "last_holdout_identity": last,
    }
    return HoldoutBundle(
        examples=tuple(holdout_examples),
        dataset_indices=dataset_indices,
        original_masks=original_masks,
        actual=actual,
        mase_scales=scales,
        cells=cells,
        target_start_hours=target_hours,
        history_end_hours=history_hours,
        identity_rows=tuple(identity_rows),
        identity_sha256=identity_sha256,
        dataset_report=report,
        frozen_thresholds=frozen_thresholds,
    )


def scenario_name(mechanism: str, requested_rate: float) -> str:
    if requested_rate == 0.0:
        return "clean"
    if mechanism == "recent_tail":
        return f"timeline_tail_{requested_rate:.2f}"
    return f"{mechanism}_{requested_rate:.2f}"


def scenario_specs(*, smoke: bool) -> tuple[tuple[str, float], ...]:
    if smoke:
        return (("mcar", 0.0), ("block", 0.20))
    rows: list[tuple[str, float]] = [("mcar", 0.0)]
    for mechanism in ROBUSTNESS_MECHANISMS:
        for requested_rate in ROBUSTNESS_RATES[1:]:
            rows.append((mechanism, requested_rate))
    if len(rows) != 17 or len(set(rows)) != 17:
        raise RuntimeError("Revision-8 scenario inventory must contain 17 unique rows")
    return tuple(rows)


def _mechanism_display(mechanism: str) -> str:
    return "timeline_tail" if mechanism == "recent_tail" else mechanism


def corrupt_examples(
    examples: Sequence[BacktestExample], additional_missing: np.ndarray
) -> tuple[BacktestExample, ...]:
    """Apply an indicator-level mask before every original feature aggregate."""
    removed = np.asarray(additional_missing, dtype=bool)
    if removed.shape != (len(examples), INPUT_HOURS, TARGET_COUNT):
        raise ValueError(f"additional missing mask has unexpected shape: {removed.shape}")
    output: list[BacktestExample] = []
    for request_index, example in enumerate(examples):
        rows: list[TrafficRow] = []
        for history_index, row in enumerate(example.window.rows):
            metrics = tuple(
                None
                if removed[request_index, history_index, metric]
                else row.metrics[metric]
                for metric in range(TARGET_COUNT)
            )
            rows.append(replace(row, metrics=metrics))
        window = replace(example.window, rows=tuple(rows))
        output.append(BacktestExample(window=window, actuals=example.actuals))
    return tuple(output)


def _load_original_baseline(source: Path) -> tuple[BaselineConfig, dict[str, object]]:
    manifest_path = source / "cache_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    selected = manifest.get("cache_config", {}).get("seasonal_baseline", {})
    if selected.get("name") != "weekly_median_s097":
        raise ValueError("Revision-3 Original WLCR seasonal selection changed")
    weights = tuple(float(value) for value in selected.get("weights", ()))
    scales = tuple(float(value) for value in selected.get("scales", ()))
    if len(weights) != 6 or len(scales) != TARGET_COUNT:
        raise ValueError("Revision-3 baseline configuration is malformed")
    return BaselineConfig(str(selected["name"]), weights, scales), {
        "source": str(manifest_path),
        "selected": selected,
        "source_sha256": sha256_file(manifest_path),
    }


def _count_leaf_values(tree: Mapping[str, object]) -> int:
    if "leaf_value" in tree:
        return 1
    return _count_leaf_values(tree["left_child"]) + _count_leaf_values(
        tree["right_child"]
    )


def _load_cpu_boosters(
    root: Path, source: Path
) -> tuple[list[Any], dict[str, object], list[dict[str, object]]]:
    """Load the hash-verified GPU-trained text models as in-memory CPU models."""
    import lightgbm as lgb

    allowed = (root / OUTPUT_ROOT / "lightgbm").resolve(strict=False)
    if source != allowed and not source.is_relative_to(allowed):
        raise ValueError("traffic-only model source must remain under artifacts/reproduction/lightgbm")
    manifest_path = source / "cache_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    config = manifest.get("cache_config")
    if not isinstance(config, dict):
        raise ValueError("Original WLCR cache manifest lacks cache_config")
    if config.get("experiment_version") != "traffic_only_73d_reproduction_v1":
        raise ValueError("source is not a regenerated 73-feature traffic-only model")
    if config.get("variant") != "traffic_only_73d":
        raise ValueError("source is not the registered 73-feature traffic-only variant")
    rounds = tuple(int(value) for value in config.get("rounds", ()))
    if rounds != ORIGINAL_WLCR_ROUNDS:
        raise ValueError(f"Original WLCR rounds changed: {rounds}")
    selected = config.get("selected_feature_names")
    if (
        not isinstance(selected, list)
        or len(selected) != TARGET_COUNT
        or any(not isinstance(item, list) or len(item) != 73 for item in selected)
        or any(item != selected[0] for item in selected[1:])
    ):
        raise ValueError("Original WLCR must expose one shared 73D traffic-only schema")
    model_records = manifest.get("models")
    if not isinstance(model_records, list) or len(model_records) != TARGET_COUNT:
        raise ValueError("Original WLCR manifest must list exactly four boosters")

    boosters: list[Any] = []
    provenance: list[dict[str, object]] = [file_provenance(root, manifest_path)]
    tree_counts: list[int] = []
    leaf_counts: list[int] = []
    for metric, record in enumerate(model_records):
        expected_name = f"metric_{metric}.txt"
        if record.get("file") != expected_name:
            raise ValueError(f"Original WLCR booster order mismatch at metric {metric}")
        path = source / expected_name
        asset = file_provenance(root, path)
        if (
            asset["size_bytes"] != int(record.get("size_bytes", -1))
            or asset["sha256"] != record.get("sha256")
        ):
            raise ValueError(f"Original WLCR booster hash mismatch: {path}")
        # LightGBM 4.6 can fail when reset_parameter changes a GPU-trained
        # model.  Reparse a transient string after changing exactly the one
        # device marker; source tree text remains hash-verified and untouched.
        model_text = path.read_text(encoding="utf-8")
        if model_text.count("[device_type: gpu]") != 1:
            raise ValueError("frozen Original WLCR model lacks one GPU device marker")
        cpu_model_text = model_text.replace(
            "[device_type: gpu]", "[device_type: cpu]"
        )
        booster = lgb.Booster(model_str=cpu_model_text)
        dumped = booster.dump_model()
        trees = dumped.get("tree_info", [])
        tree_counts.append(len(trees))
        leaf_counts.append(
            sum(_count_leaf_values(item["tree_structure"]) for item in trees)
        )
        boosters.append(booster)
        provenance.append(
            {
                **asset,
                "metric": int(metric),
                "trees": int(tree_counts[-1]),
                "learned_leaf_values": int(leaf_counts[-1]),
            }
        )
    metadata = {
        "feature_count": 73,
        "selected_feature_names": selected[0],
        "rounds": list(rounds),
        "lightgbm_version": str(lgb.__version__),
        "cpu_inference_model_loading": (
            "in-memory LightGBM model string with only [device_type: gpu] "
            "rewritten to [device_type: cpu]; hash-verified source tree text is unchanged"
        ),
        "tree_count_per_target": tree_counts,
        "tree_count_total": int(sum(tree_counts)),
        "learned_leaf_values_per_target": leaf_counts,
        "learned_leaf_values_total": int(sum(leaf_counts)),
        "frozen_metadata_scalars": {
            "seasonal_baseline_weights": 6,
            "seasonal_baseline_scales": 4,
            "selected_feature_indices": 73,
            "boosting_rounds": 4,
        },
    }
